#!/usr/bin/python3
"""wmlayout.py — the ONE root-resolution function for the whole tool.

Every path the tool needs — its own tree, the two writable caches, the root helper, the auxiliary
binaries, the LaunchDaemon plist and the sudoers rule — is derived from the location of *this file*.
Nothing here reads the current directory, a hardcoded repository path or an environment variable,
so the identical code runs from the development checkout and from
`Sturgeon.app/Contents/Resources/wmship`.

Two layouts, selected by a marker file called `BUNDLE` at the tool root (the app tree shape is
also recognised without it):

    checkout   root = <repo>/work
               caches stay in the tree:      <repo>/work/sites.json, <repo>/work/wmship/profile.json

    bundle     root = Sturgeon.app/Contents/Resources/wmship
               writable state:               ~/Library/Application Support/Sturgeon/
                 sites.json                  the site cache (regenerated by wmlocate)
                 profile.json                the build profile, seeded from the bundled copy
                 logs/                       setup/teardown and daemon logs
               runtime state (unchanged):    /tmp/wmship   (root-owned, ephemeral)

The user state directory is resolved from an explicit uid: `STURGEON_UID` when a caller sets it
(wmship.sh exports it; asroot passes it to every python child), else the /dev/console owner when
there is a real console login, else sudo's SUDO_UID/SUDO_USER, else the effective uid.  uid 0 is
only chosen when every input is root or absent, so a root-owned console (headless, SSH, CI) no
longer sends the cache to /var/root.  The daemon gets the same uid through its plist.  Files
created by a root run are handed back to that user (`adopt()`), so a later unprivileged `doctor`
can still update the cache.

Usage:
    wmlayout.py [--uid <n>] shell   shell assignments for wmship.sh / setup.sh / teardown.sh
    wmlayout.py [--uid <n>] json    the same, as JSON
    wmlayout.py plist <path|->      the LaunchDaemon plist, resolved for this location
    wmlayout.py state-dir           create (on demand) and print the writable state dir
    wmlayout.py paths               human-readable listing
"""
import json
import os
import pwd
import shlex
import sys

APP_NAME = "Sturgeon"
D = "/tmp/wmship"                                  # runtime state (root-owned, unchanged)
PY = "/usr/bin/python3"
PLIST_LABEL = "com.stagemgr.wmshipd"
PLIST_DEST = "/Library/LaunchDaemons/%s.plist" % PLIST_LABEL
SUDOERS_CHECKOUT = "/etc/sudoers.d/stage-mgr"
SUDOERS_BUNDLE = "/etc/sudoers.d/stage-pilot"

# Auxiliary binaries, by logical name: (bundle-relative, checkout-relative).
# The bundle carries one flat `bin/`; the checkout keeps each round's own build directory.
_BINS = {
    "asroot":      ("bin/asroot",          "asroot"),
    "wmx":         ("bin/wmx",             "re/round24/wmx"),
    "wmhb":        ("wmship/wmhb",         "wmship/wmhb"),
    "wmcls":       ("wmship/wmcls",        "wmship/wmcls"),
    "wmobs":       ("wm/wmobs",            "wm/wmobs"),
    "wmkey":       ("wm/wmkey",            "wm/wmkey"),
    "r21obs":      ("bin/r21obs",          "re/round21/r21obs"),
    "r21probe":    ("bin/r21probe",        "re/round21/r21probe"),
    "r21move":     ("bin/r21move",         "re/round21/r21move"),
    "r21scroll":   ("bin/r21scroll",       "re/round21/r21scroll"),
    "r21gesture":  ("bin/r21gesture",      "re/round21/r21gesture"),
    "r8state":     ("bin/r8state",         "re/round8/r8state"),
    "r20click":    ("bin/r20click",        "re/round20/r20click"),
    "r19ax":       ("bin/r19ax",           "re/round19/r19ax"),
}

_CACHE = {}


# ---------------------------------------------------------------- discovery
def root():
    """The tool root: the directory this file lives in, symlinks resolved.

    realpath matters: the sudoers rule grants exactly one path, so "where am I" must be the same
    answer the rule uses, not a symlinked alias of it."""
    if "root" not in _CACHE:
        _CACHE["root"] = os.path.dirname(os.path.realpath(__file__))
    return _CACHE["root"]


def is_bundle(r=None):
    r = r or root()
    if os.path.isfile(os.path.join(r, "BUNDLE")):
        return True
    # app-tree shape: <app>.app/Contents/Resources/wmship
    return (os.path.basename(r) == "wmship"
            and os.path.basename(os.path.dirname(r)) == "Resources"
            and os.path.basename(os.path.dirname(os.path.dirname(r))) == "Contents")


def app_dir():
    """The enclosing .app, or None in a checkout."""
    if not is_bundle():
        return None
    # <app>.app/Contents/Resources/wmship -> <app>.app
    return os.path.dirname(os.path.dirname(os.path.dirname(root())))


# ---------------------------------------------------------------- the human this install belongs to
def _pw(name):
    try:
        return pwd.getpwnam(name)
    except KeyError:
        return None


def console_uid():
    """The uid that owns /dev/console, or None when it cannot be read.

    uid 0 means "there is no console login" (a headless machine, SSH without a GUI session, CI),
    not "the state belongs to root": that is the case this module must not mistake for a user."""
    try:
        return os.stat("/dev/console").st_uid
    except OSError:
        return None


def _env_uid(env, key):
    """A uid from the environment: a decimal uid, or a user name resolved through passwd."""
    v = (env.get(key) or "").strip()
    if not v:
        return None
    if v.isdigit():
        return int(v)
    pw = _pw(v)
    return pw.pw_uid if pw else None


def resolve_uid(console, env, euid):
    """Which user's writable state this run reads and writes.  Pure over its three inputs.

    Precedence: STURGEON_UID (explicit: set by wmship.sh and by asroot for its children) ->
    the /dev/console owner when it is a real login -> SUDO_UID/SUDO_USER -> the effective uid.
    uid 0 is chosen only when every input is root or absent; a root-owned console (headless, SSH,
    CI) must never send a user's cache to /var/root."""
    for candidate in (_env_uid(env, "STURGEON_UID"),
                      console,
                      _env_uid(env, "SUDO_UID"),
                      _env_uid(env, "SUDO_USER"),
                      euid):
        if candidate is not None and candidate != 0:
            return candidate
    return 0


_UID = {}


def resolved_uid():
    """resolve_uid() for this process; cached, because every path derivation uses it."""
    if "uid" not in _UID:
        _UID["uid"] = resolve_uid(console_uid(), os.environ, os.geteuid())
    return _UID["uid"]


def set_uid(uid):
    """Pin the answer for this process (the --uid option, or a caller that already resolved it)."""
    _UID["uid"] = int(uid)


def console_user():
    uid = resolved_uid()
    try:
        return pwd.getpwuid(uid).pw_name
    except KeyError:
        return "root" if uid == 0 else str(uid)


def user_home(uid=None):
    uid = resolved_uid() if uid is None else int(uid)
    try:
        return pwd.getpwuid(uid).pw_dir
    except KeyError:
        return os.path.expanduser("~")


# ---------------------------------------------------------------- layout
def wmship_dir():
    """Where install.py / ctl.py / wmshipd.py / the payload live."""
    r = root()
    sub = os.path.join(r, "wmship")
    return sub if os.path.isdir(sub) else r


def state_dir_for(home):
    """The writable state directory for a home directory (no environment, no passwd)."""
    return os.path.join(home, "Library", "Application Support", APP_NAME)


def state_dir(uid=None):
    """The writable user state directory (bundle only; the checkout writes in its own tree)."""
    if not is_bundle():
        return root()
    return state_dir_for(user_home(uid))


def ensure_state_dir():
    """Create the state dir (and logs/) on demand, owned by the console user."""
    d = state_dir()
    for sub in (d, os.path.join(d, "logs")):
        if not os.path.isdir(sub):
            os.makedirs(sub, exist_ok=True)
            adopt(sub)
    adopt_tree(d)                    # a root run may have created files inside before this call
    return d


def adopt_tree(d):
    """Hand every file a previous root run created in the state dir back to the console user."""
    if os.geteuid() != 0 or not is_bundle():
        return
    pw = _pw(console_user())
    if not pw:
        return
    for base, dirs, files in os.walk(d):
        for n in [base] + [os.path.join(base, f) for f in files]:
            try:
                os.chown(n, pw.pw_uid, pw.pw_gid)
            except Exception:
                pass


def adopt(path):
    """Hand a file/dir created by a root run back to the console user, so an unprivileged run can
    keep updating the same cache (a root-owned sites.json made the second `doctor` refuse)."""
    if os.geteuid() != 0 or not is_bundle():
        return
    pw = _pw(console_user())
    if not pw:
        return
    try:
        os.chown(path, pw.pw_uid, pw.pw_gid)
    except Exception:
        pass


def sites_json():
    d = ensure_state_dir() if is_bundle() else root()
    return os.path.join(d, "sites.json")


def profile_json():
    """The build profile.  In the bundle the writable copy lives in the state dir and is seeded /
    refreshed from the copy shipped inside the app: a new app version can ship a profile for a new
    WindowManager build, while anything the user derived locally is preserved."""
    seed = os.path.join(wmship_dir(), "profile.json")
    if not is_bundle():
        return seed
    d = ensure_state_dir()
    live = os.path.join(d, "profile.json")
    try:
        s = json.load(open(seed))
    except Exception:
        s = None
    if s is None:
        return live
    cur = None
    try:
        cur = json.load(open(live))
    except Exception:
        cur = None
    merged = dict(cur or {})
    sb, cb = s.get("builds") or {}, (cur or {}).get("builds") or {}
    if sb or cb:
        b = dict(cb)
        b.update(sb)                     # the shipped profile wins for the keys it knows
        merged["builds"] = b
    for k, v in s.items():
        if k != "builds":
            merged.setdefault(k, v)
    if cur != merged:
        try:
            with open(live, "w") as f:
                json.dump(merged, f, indent=1, sort_keys=True)
            adopt(live)
        except Exception:
            return live if os.path.exists(live) else seed
    return live


def bin_path(name):
    """Absolute path of an auxiliary binary for this layout (existing one preferred)."""
    r = root()
    b, c = _BINS[name]
    first = os.path.join(r, b)
    second = os.path.join(r, c)
    if os.path.exists(first):
        return first
    if os.path.exists(second):
        return second
    return first if is_bundle() else second


def sudoers_path():
    return SUDOERS_BUNDLE if is_bundle() else SUDOERS_CHECKOUT


def asroot():
    return bin_path("asroot")


def sudoers_line():
    return "%s ALL=(root) NOPASSWD: %s" % (console_user(), asroot())


def plist_text():
    """The LaunchDaemon, with this location's paths substituted.  A path baked into a shipped
    plist is exactly the relocation bug this module exists to remove.

    STURGEON_UID carries this invocation's resolved user into the daemon, so the root daemon's
    children read the same cache the user's commands do even when /dev/console is root."""
    p = os.path.join(wmship_dir(), "com.stagemgr.wmshipd.plist")
    with open(p) as f:
        text = f.read()
    return (text.replace("__PYTHON__", PY)
                .replace("__WMSHIPD__", os.path.join(wmship_dir(), "wmshipd.py"))
                .replace("__D__", D)
                .replace("__UID__", str(resolved_uid())))


# ---------------------------------------------------------------- one dict for everyone
def layout():
    r = root()
    b = is_bundle()
    return {
        "layout": "bundle" if b else "checkout",
        "root": r,
        "app": app_dir() or "",
        "wmship": wmship_dir(),
        "wm": os.path.join(r, "wm"),
        "bin": os.path.join(r, "bin"),
        "asroot": asroot(),
        "wmlocate": os.path.join(r, "wmlocate.py"),
        "sites": sites_json(),
        "profile": profile_json(),
        "state_dir": state_dir(),
        "logs": os.path.join(state_dir(), "logs"),
        "runtime": D,
        "wmx": bin_path("wmx"),
        "wmhb": bin_path("wmhb"),
        "wmcls": bin_path("wmcls"),
        "wmobs": bin_path("wmobs"),
        "r21obs": bin_path("r21obs"),
        "plist": PLIST_DEST,
        "plist_label": PLIST_LABEL,
        "sudoers": sudoers_path(),
        "user": console_user(),
        "uid": resolved_uid(),
        "home": user_home(),
        "python": PY,
    }


_SHELL_VARS = (("LAYOUT", "layout"), ("ROOT", "root"), ("APP", "app"),
               ("WMSHIP", "wmship"), ("WMDIR", "wm"), ("BINDIR", "bin"),
               ("ASROOT", "asroot"), ("WMLOCATE", "wmlocate"),
               ("SITES", "sites"), ("PROFILE", "profile"),
               ("STATE_DIR", "state_dir"), ("LOGS", "logs"),
               ("WMX", "wmx"), ("WMHB", "wmhb"), ("WMCLS", "wmcls"),
               ("WMOBS", "wmobs"), ("R21OBS", "r21obs"),
               ("PLIST", "plist"), ("PLIST_LABEL", "plist_label"),
               ("SUDOERS", "sudoers"), ("CONSOLE_USER", "user"),
               ("STURGEON_UID", "uid"), ("PY", "python"))


def _take_uid(argv):
    """Consume a leading --uid <n> / --uid=<n>; returns (uid or None, remaining args)."""
    if not argv:
        return None, argv
    a = argv[0]
    if a == "--uid":
        if len(argv) < 2 or not argv[1].isdigit():
            sys.stderr.write("wmlayout: --uid needs a decimal uid\n")
            raise SystemExit(2)
        return int(argv[1]), argv[2:]
    if a.startswith("--uid="):
        v = a.split("=", 1)[1]
        if not v.isdigit():
            sys.stderr.write("wmlayout: --uid needs a decimal uid\n")
            raise SystemExit(2)
        return int(v), argv[1:]
    return None, argv


def main(argv):
    uid, rest = _take_uid(argv[1:])
    if uid is not None:
        set_uid(uid)
    cmd = rest[0] if rest else "paths"
    L = layout()
    if cmd == "shell":
        for var, key in _SHELL_VARS:
            print("%s=%s" % (var, shlex.quote(str(L[key]))))
        print("D=%s" % shlex.quote(D))
        return 0
    if cmd == "json":
        print(json.dumps(L, indent=1, sort_keys=True))
        return 0
    if cmd == "paths":
        for k in sorted(L):
            print("%-12s %s" % (k, L[k]))
        return 0
    if cmd == "state-dir":
        print(ensure_state_dir())
        return 0
    if cmd == "sites":
        print(sites_json())
        return 0
    if cmd == "profile":
        print(profile_json())
        return 0
    if cmd == "asroot":
        print(asroot())
        return 0
    if cmd == "sudoers-line":
        print(sudoers_line())
        return 0
    if cmd == "plist":
        out = rest[1] if len(rest) > 1 else "-"
        text = plist_text()
        if out == "-":
            sys.stdout.write(text)
        else:
            with open(out, "w") as f:
                f.write(text)
        return 0
    sys.stderr.write("usage: wmlayout.py [--uid <n>] "
                     "shell|json|paths|state-dir|sites|profile|asroot|sudoers-line|plist <path|->\n")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
